using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace Severnbli.LocalizationCodegen.Editor
{
    /// <summary>Pure text helpers used while generating code.</summary>
    internal static class CodegenText
    {
        public const string Marker = "// <auto-generated by Localization Codegen>";

        public static readonly HashSet<string> Keywords = new HashSet<string>(StringComparer.Ordinal)
        {
            "abstract","as","base","bool","break","byte","case","catch","char","checked","class","const","continue",
            "decimal","default","delegate","do","double","else","enum","event","explicit","extern","false","finally",
            "fixed","float","for","foreach","goto","if","implicit","in","int","interface","internal","is","lock","long",
            "namespace","new","null","object","operator","out","override","params","private","protected","public",
            "readonly","ref","return","sbyte","sealed","short","sizeof","stackalloc","static","string","struct",
            "switch","this","throw","true","try","typeof","uint","ulong","unchecked","unsafe","ushort","using",
            "virtual","void","volatile","while"
        };

        /// <summary>
        /// Members inherited from <see cref="object"/> that would otherwise produce CS0108 when a key matches.
        /// </summary>
        public static readonly string[] ObjectMemberNames =
        {
            "Equals", "ReferenceEquals", "GetHashCode", "ToString", "GetType", "MemberwiseClone", "Finalize"
        };

        static readonly string[] s_WindowsReserved =
        {
            "CON", "PRN", "AUX", "NUL",
            "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8", "COM9",
            "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9"
        };

        static readonly HashSet<string> s_WindowsReservedSet =
            new HashSet<string>(s_WindowsReserved, StringComparer.OrdinalIgnoreCase);

        /// <summary>Escapes a value so it can be placed inside a regular C# string literal.</summary>
        public static string Literal(string value)
        {
            value = value ?? "";
            var sb = new StringBuilder(value.Length + 2).Append('"');
            for (var i = 0; i < value.Length; i++)
            {
                var c = value[i];
                switch (c)
                {
                    case '\\': sb.Append(@"\\"); continue;
                    case '"': sb.Append("\\\""); continue;
                    case '\n': sb.Append(@"\n"); continue;
                    case '\r': sb.Append(@"\r"); continue;
                    case '\t': sb.Append(@"\t"); continue;
                }

                if (char.IsHighSurrogate(c) && i + 1 < value.Length && char.IsLowSurrogate(value[i + 1]))
                {
                    sb.Append(c).Append(value[++i]);
                    continue;
                }

                if (c < 0x20 || (c >= 0x7F && c <= 0x9F) || c == '\u2028' || c == '\u2029' || char.IsSurrogate(c))
                    sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                else
                    sb.Append(c);
            }
            return sb.Append('"').ToString();
        }

        /// <summary>
        /// Makes a value safe for a single-line <c>//</c> or <c>///</c> comment. Every character that can terminate
        /// or corrupt the comment is replaced with a space.
        /// </summary>
        public static string SanitizeComment(string value)
        {
            if (string.IsNullOrEmpty(value))
                return "";

            var sb = new StringBuilder(value.Length);
            for (var i = 0; i < value.Length; i++)
            {
                var c = value[i];
                if (c == '\r' || c == '\n')
                {
                    sb.Append(' ');
                    continue;
                }

                if (c < 0x20 || c == '\u0085' || c == '\u2028' || c == '\u2029')
                {
                    sb.Append(' ');
                    continue;
                }

                if (char.IsHighSurrogate(c))
                {
                    if (i + 1 < value.Length && char.IsLowSurrogate(value[i + 1]))
                    {
                        sb.Append(c).Append(value[++i]);
                    }
                    else
                    {
                        sb.Append(' ');
                    }
                    continue;
                }

                if (char.IsLowSurrogate(c))
                {
                    sb.Append(' ');
                    continue;
                }

                sb.Append(c);
            }
            return sb.ToString();
        }

        /// <summary>Escapes text for use inside an XML doc comment.</summary>
        public static string EscapeXml(string value)
        {
            value = value ?? "";
            return value
                .Replace("&", "&amp;")
                .Replace("<", "&lt;")
                .Replace(">", "&gt;")
                .Replace("\"", "&quot;")
                .Replace("'", "&apos;");
        }

        /// <summary>Truncates a string without splitting a surrogate pair.</summary>
        public static string Truncate(string value, int maxLength)
        {
            if (string.IsNullOrEmpty(value) || value.Length <= maxLength)
                return value ?? "";

            var length = maxLength;
            if (length > 0 && char.IsHighSurrogate(value[length - 1]))
                length--;
            return value.Substring(0, length) + "...";
        }

        /// <summary>
        /// Converts an arbitrary key to a C# identifier using the historical behaviour: every invalid UTF-16 unit
        /// becomes an underscore and runs are preserved.
        /// </summary>
        public static string ToIdentifier(string value)
            => ToIdentifier(value, false);

        /// <summary>
        /// Converts an arbitrary key to a C# identifier.
        /// When <paramref name="compact"/> is true consecutive invalid characters collapse to one underscore,
        /// trailing underscores are removed and surrogate pairs are treated as a single character.
        /// </summary>
        public static string ToIdentifier(string value, bool compact)
        {
            value = value ?? "";
            if (!compact)
            {
                var simple = new StringBuilder();
                foreach (var c in value)
                    simple.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');

                var result = simple.ToString();
                if (result.Length == 0)
                    return "_";
                if (char.IsDigit(result[0]))
                    result = "_" + result;
                return Keywords.Contains(result) ? "@" + result : result;
            }

            var sb = new StringBuilder(value.Length);
            var pendingUnderscore = false;
            for (var i = 0; i < value.Length; i++)
            {
                var c = value[i];
                var isPair = i + 1 < value.Length && char.IsSurrogatePair(c, value[i + 1]);
                var isValid = isPair ? char.IsLetterOrDigit(value, i) : (char.IsLetterOrDigit(c) || c == '_');

                if (isValid)
                {
                    if (pendingUnderscore && sb.Length > 0)
                        sb.Append('_');
                    pendingUnderscore = false;
                    sb.Append(c);
                    if (isPair)
                        sb.Append(value[++i]);
                }
                else
                {
                    pendingUnderscore = true;
                    if (isPair)
                        i++;
                }
            }

            var compacted = sb.ToString();
            if (compacted.Length == 0)
                return "_";
            if (char.IsDigit(compacted[0]))
                compacted = "_" + compacted;
            return Keywords.Contains(compacted) ? "@" + compacted : compacted;
        }

        /// <summary>Builds a camelCase identifier from a smart string variable name.</summary>
        public static string ToCamelIdentifier(string value)
        {
            var words = SplitWords(value);
            if (words.Count == 0)
                return "_";

            var sb = new StringBuilder();
            for (var i = 0; i < words.Count; i++)
            {
                var word = words[i];
                if (i == 0)
                {
                    sb.Append(char.ToLowerInvariant(word[0]));
                    sb.Append(word.Substring(1));
                }
                else
                {
                    sb.Append(char.ToUpperInvariant(word[0]));
                    sb.Append(word.Substring(1));
                }
            }

            var result = sb.ToString();
            if (char.IsDigit(result[0]))
                result = "_" + result;
            return Keywords.Contains(result) ? "@" + result : result;
        }

        /// <summary>Builds a PascalCase identifier from a table key.</summary>
        public static string ToPascalCase(string value)
        {
            var words = SplitWords(value);
            if (words.Count == 0)
                return "_";

            var sb = new StringBuilder();
            foreach (var word in words)
            {
                sb.Append(char.ToUpperInvariant(word[0]));
                sb.Append(word.Substring(1));
            }

            var result = sb.ToString();
            if (char.IsDigit(result[0]))
                result = "_" + result;
            return Keywords.Contains(result) ? "@" + result : result;
        }

        static List<string> SplitWords(string value)
        {
            var words = new List<string>();
            value = value ?? "";
            var current = new StringBuilder();

            for (var i = 0; i < value.Length; i++)
            {
                var c = value[i];
                var isPair = i + 1 < value.Length && char.IsSurrogatePair(c, value[i + 1]);
                var valid = isPair ? char.IsLetterOrDigit(value, i) : (char.IsLetterOrDigit(c) || c == '_');

                if (valid)
                {
                    if (c == '_')
                    {
                        if (current.Length > 0)
                        {
                            words.Add(current.ToString());
                            current.Length = 0;
                        }
                        continue;
                    }

                    current.Append(c);
                    if (isPair)
                        current.Append(value[++i]);
                }
                else if (current.Length > 0)
                {
                    words.Add(current.ToString());
                    current.Length = 0;
                }
            }

            if (current.Length > 0)
                words.Add(current.ToString());
            return words;
        }

        /// <summary>Appends a numeric suffix until the name is unique.</summary>
        public static string Unique(string name, ISet<string> used)
        {
            var candidate = name;
            var i = 2;
            while (!used.Add(candidate))
                candidate = name + "_" + i++;
            return candidate;
        }

        /// <summary>Returns true when the value is a reserved device file name on Windows.</summary>
        public static bool IsWindowsReservedFileName(string value)
        {
            if (string.IsNullOrEmpty(value))
                return false;

            var name = value.TrimStart('@');
            var dot = name.IndexOf('.');
            if (dot >= 0)
                name = name.Substring(0, dot);
            name = name.TrimEnd('_');
            return s_WindowsReservedSet.Contains(name);
        }
    }
}
