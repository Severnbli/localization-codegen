using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEditor.Localization;
using UnityEngine;
using UnityEngine.Localization.Tables;

namespace Severnbli.LocalizationCodegen.Editor
{
    public static class CodeGenerator
    {
        public const string Marker = "// <auto-generated by Localization Codegen>";
        public const string RuntimeNamespace = "Severnbli.LocalizationCodegen";

        static readonly HashSet<string> Keywords = new HashSet<string>
        {
            "abstract","as","base","bool","break","byte","case","catch","char","checked","class","const","continue",
            "decimal","default","delegate","do","double","else","enum","event","explicit","extern","false","finally",
            "fixed","float","for","foreach","goto","if","implicit","in","int","interface","internal","is","lock","long",
            "namespace","new","null","object","operator","out","override","params","private","protected","public",
            "readonly","ref","return","sbyte","sealed","short","sizeof","stackalloc","static","string","struct",
            "switch","this","throw","true","try","typeof","uint","ulong","unchecked","unsafe","ushort","using",
            "virtual","void","volatile","while"
        };

        public static int Generate()
        {
            var settings = CodegenSettings.instance;
            var folder = (settings.OutputFolder ?? "").Trim().TrimEnd('/', '\\');
            if (string.IsNullOrEmpty(folder) || !folder.StartsWith("Assets"))
            {
                Debug.LogError("[Localization Codegen] Output folder must be inside the Assets folder.");
                return -1;
            }

            Directory.CreateDirectory(folder);
            var written = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var usedClassNames = new HashSet<string> { "LocalizedTables" };
            var changed = 0;

            if (settings.GenerateStringTables)
            {
                foreach (var collection in LocalizationEditorSettings.GetStringTableCollections())
                    if (WriteCollection(collection, false, folder, settings.Namespace, usedClassNames, written))
                        changed++;
            }

            if (settings.GenerateAssetTables)
            {
                foreach (var collection in LocalizationEditorSettings.GetAssetTableCollections())
                    if (WriteCollection(collection, true, folder, settings.Namespace, usedClassNames, written))
                        changed++;
            }

            foreach (var file in Directory.GetFiles(folder, "*.g.cs"))
            {
                if (written.Contains(Path.GetFullPath(file)) || !IsGenerated(file))
                    continue;
                AssetDatabase.DeleteAsset(file.Replace('\\', '/'));
                changed++;
            }

            if (changed > 0)
                AssetDatabase.Refresh();

            Debug.Log($"[Localization Codegen] Generated {written.Count} table class file(s) in {folder} ({changed} changed).");
            return changed;
        }

        static bool IsGenerated(string path)
        {
            using (var reader = new StreamReader(path))
                return reader.ReadLine() == Marker;
        }

        static bool WriteCollection(LocalizationTableCollection collection, bool isAsset, string folder, string ns,
            HashSet<string> usedClassNames, HashSet<string> written)
        {
            var tableName = collection.TableCollectionName;
            var className = Unique(ToIdentifier(tableName), usedClassNames);
            var path = Path.Combine(folder, className.TrimStart('@') + ".g.cs");
            written.Add(Path.GetFullPath(path));
            var content = Build(collection, isAsset, tableName, className, ns);

            if (File.Exists(path) && File.ReadAllText(path) == content)
                return false;
            File.WriteAllText(path, content, new UTF8Encoding(false));
            return true;
        }

        static string Build(LocalizationTableCollection collection, bool isAsset, string tableName, string className, string ns)
        {
            var sb = new StringBuilder();
            var hasNs = !string.IsNullOrWhiteSpace(ns);
            var indent = hasNs ? "    " : "";
            sb.Append(Marker).Append('\n');
            sb.Append("// Table collection: ").Append(tableName.Replace('\n', ' ').Replace('\r', ' ')).Append('\n');
            if (hasNs)
                sb.Append("namespace ").Append(string.Join(".", Array.ConvertAll(ns.Split('.'), ToIdentifier))).Append('\n').Append("{\n");

            sb.Append(indent).Append("public static class ").Append(className).Append('\n');
            sb.Append(indent).Append("{\n");
            sb.Append(indent).Append("    public const string TableName = ").Append(Literal(tableName)).Append(";\n");

            var used = new HashSet<string> { "TableName", className };
            var entries = new List<SharedTableData.SharedTableEntry>(collection.SharedData.Entries);
            entries.Sort((a, b) => string.CompareOrdinal(a.Key, b.Key));
            foreach (var entry in entries)
            {
                if (string.IsNullOrEmpty(entry.Key))
                    continue;
                var name = Unique(ToIdentifier(entry.Key), used);
                sb.Append('\n');
                if (isAsset)
                {
                    var type = AssetTypeName(collection as AssetTableCollection, entry);
                    sb.Append(indent).Append("    public static ").Append(type).Append(' ').Append(name)
                      .Append(" => global::").Append(RuntimeNamespace).Append(".LocalizedTables.GetAsset<").Append(type)
                      .Append(">(TableName, ").Append(Literal(entry.Key)).Append(");\n");
                }
                else
                {
                    sb.Append(indent).Append("    public static string ").Append(name)
                      .Append(" => global::").Append(RuntimeNamespace).Append(".LocalizedTables.GetString(TableName, ")
                      .Append(Literal(entry.Key)).Append(");\n");
                }
            }

            sb.Append(indent).Append("}\n");
            if (hasNs)
                sb.Append("}\n");
            return sb.ToString();
        }

        static string AssetTypeName(AssetTableCollection collection, SharedTableData.SharedTableEntry entry)
        {
            Type type = null;
            try { type = collection?.GetEntryAssetType(entry.Id); }
            catch { }

            if (type == null || !type.IsPublic || type.IsGenericType ||
                type.Assembly.GetName().Name.Contains("Editor") || !typeof(UnityEngine.Object).IsAssignableFrom(type))
                return "global::UnityEngine.Object";
            return "global::" + type.FullName.Replace('+', '.');
        }

        static string Literal(string value)
        {
            var sb = new StringBuilder("\"");
            foreach (var c in value)
            {
                switch (c)
                {
                    case '\\': sb.Append("\\\\"); break;
                    case '"': sb.Append("\\\""); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (c < 32) sb.Append("\\u").Append(((int)c).ToString("x4"));
                        else sb.Append(c);
                        break;
                }
            }
            return sb.Append('"').ToString();
        }

        public static string ToIdentifier(string value)
        {
            var sb = new StringBuilder();
            foreach (var c in value ?? "")
            {
                sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            }

            var result = sb.ToString();
            if (result.Length == 0)
                return "_";
            if (char.IsDigit(result[0]))
                result = "_" + result;
            return Keywords.Contains(result) ? "@" + result : result;
        }

        static string Unique(string name, HashSet<string> used)
        {
            var candidate = name;
            var i = 2;
            while (!used.Add(candidate))
                candidate = name + "_" + i++;
            return candidate;
        }
    }
}

