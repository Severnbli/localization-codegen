using System;
using System.Collections.Generic;
using System.Linq;
using NUnit.Framework;

namespace Severnbli.LocalizationCodegen.Editor.Tests
{
    public class EmitterTests
    {
        static TableModel StringModel(string name, params long[] ids)
        {
            var model = new TableModel { Name = name };
            foreach (var id in ids)
            {
                model.Entries.Add(new EntryModel
                {
                    Id = id,
                    Key = "Key" + id
                });
            }
            return model;
        }

        static TableModel Model(string name, bool isAsset, params (long Id, string Key)[] entries)
        {
            var model = new TableModel { Name = name, IsAsset = isAsset };
            foreach (var entry in entries)
            {
                model.Entries.Add(new EntryModel
                {
                    Id = entry.Id,
                    Key = entry.Key,
                    AssetTypeName = isAsset ? "global::UnityEngine.Object" : null
                });
            }
            return model;
        }

        static EmitOptions LegacyOptions()
        {
            return new EmitOptions
            {
                Namespace = "Localization",
                UseRuntimeAlias = false,
                SmartStrings = SmartStringMode.Off,
                Naming = NamingConvention.Keep
            };
        }

        [Test]
        public void DefaultOptions_ReproduceLegacyOutput()
        {
            var model = Model("Ui", false, (2L, "Title"), (1L, "Greeting"));
            var options = LegacyOptions();
            CodeEmitter.AssignClassNames(new[] { model }, options);

            var expected =
                "// <auto-generated by Localization Codegen>\n" +
                "// Table collection: Ui\n" +
                "namespace Localization\n" +
                "{\n" +
                "    public static class Ui\n" +
                "    {\n" +
                "        public const string TableName = \"Ui\";\n" +
                "\n" +
                "        public static string Greeting => global::Severnbli.LocalizationCodegen.LocalizedTables.GetString(TableName, \"Greeting\");\n" +
                "\n" +
                "        public static string Title => global::Severnbli.LocalizationCodegen.LocalizedTables.GetString(TableName, \"Title\");\n" +
                "    }\n" +
                "}\n";

            Assert.AreEqual(expected, CodeEmitter.Emit(model, options));
        }

        [Test]
        public void RuntimeAlias_IsDeclaredOnceAndUsedByEveryMember()
        {
            var model = Model("Ui", false, (1L, "Greeting"), (2L, "Title"));
            var options = new EmitOptions
            {
                Namespace = "Localization",
                UseRuntimeAlias = true,
                SmartStrings = SmartStringMode.Off
            };
            CodeEmitter.AssignClassNames(new[] { model }, options);

            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains("using __LT = global::Severnbli.LocalizationCodegen.LocalizedTables;\n", output);
            StringAssert.Contains("public static string Greeting => __LT.GetString(TableName, \"Greeting\");", output);
            StringAssert.DoesNotContain("global::Severnbli.LocalizationCodegen.LocalizedTables.GetString", output);
        }

        [Test]
        public void AssetType_SupportsNestedPublicTypes()
        {
            var model = new TableModel { Name = "Items", IsAsset = true };
            model.Entries.Add(new EntryModel
            {
                Id = 1,
                Key = "Icon",
                AssetTypeName = "global::Game.Outer.Inner"
            });

            var options = new EmitOptions { Namespace = "Localization", UseRuntimeAlias = true };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains(
                "public static global::Game.Outer.Inner Icon => __LT.GetAsset<global::Game.Outer.Inner>(TableName, \"Icon\");",
                output);
        }

        [Test]
        public void ClassNames_AreCaseInsensitiveAndDeterministic()
        {
            var first = Model("Ui", false, (1L, "A"));
            var second = Model("UI", false, (1L, "A"));
            var options = LegacyOptions();

            CodeEmitter.AssignClassNames(new[] { first, second }, options);

            Assert.IsFalse(string.Equals(first.ClassName, second.ClassName, StringComparison.OrdinalIgnoreCase));
            Assert.AreEqual("UI", second.ClassName);
            Assert.AreEqual("Ui_2", first.ClassName);
        }

        [Test]
        public void ClassNames_AvoidReservedNamespaces()
        {
            var system = Model("System", false, (1L, "A"));
            var localization = Model("Localization", false, (1L, "A"));
            var options = new EmitOptions { Namespace = "Localization" };

            CodeEmitter.AssignClassNames(new[] { system, localization }, options);

            Assert.AreEqual("SystemTable", system.ClassName);
            Assert.AreEqual("LocalizationTable", localization.ClassName);
        }

        [Test]
        public void ClassNames_AvoidWindowsDeviceNames()
        {
            var model = Model("CON", false, (1L, "A"));
            var options = new EmitOptions { Namespace = "Localization" };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            Assert.AreEqual("CON_", model.ClassName);
        }

        [Test]
        public void ClassNames_AssetCollectionWithSameNameAsStringCollectionGetsAssetsSuffix()
        {
            var strings = Model("Items", false, (1L, "A"));
            var assets = Model("Items", true, (1L, "Icon"));
            var options = new EmitOptions { Namespace = "Localization" };

            CodeEmitter.AssignClassNames(new[] { assets, strings }, options);

            Assert.AreEqual("Items", strings.ClassName);
            Assert.AreEqual("ItemsAssets", assets.ClassName);
        }

        [Test]
        public void MemberCollisions_KeepTheOldestEntryNameAndWarnDeterministically()
        {
            var model = Model("Ui", false, (2L, "Player Name"), (1L, "Player/Name"));
            var options = new EmitOptions { Namespace = "Localization", UseRuntimeAlias = true };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains("public static string Player_Name =>", output);
            StringAssert.Contains("public static string Player_Name_2 =>", output);
            // The older id (1) keeps the base name even though its key sorts later.
            StringAssert.Contains("Player_Name => __LT.GetString(TableName, \"Player/Name\");", output);
        }

        [Test]
        public void MemberNames_AvoidObjectMembers()
        {
            var model = Model("Ui", false, (1L, "Equals"), (2L, "ToString"));
            var options = new EmitOptions { Namespace = "Localization", UseRuntimeAlias = true };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains("public static string Equals_2 =>", output);
            StringAssert.Contains("public static string ToString_2 =>", output);
        }

        [Test]
        public void XmlDocs_AreEscapedAndSanitized()
        {
            var model = new TableModel { Name = "Ui" };
            model.Entries.Add(new EntryModel
            {
                Id = 1,
                Key = "Title",
                Preview = "<b>Hello</b>\u2028World"
            });

            var options = new EmitOptions
            {
                Namespace = "Localization",
                UseRuntimeAlias = true,
                XmlDocs = true
            };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains("/// <summary>&lt;b&gt;Hello&lt;/b&gt; World</summary>", output);
            StringAssert.DoesNotContain("\u2028", output);
        }

        [Test]
        public void SmartString_EmitsMethodWithPositionalParameters()
        {
            var model = new TableModel { Name = "Ui" };
            var entry = new EntryModel { Id = 1, Key = "Greeting", IsSmart = true };
            entry.Params.Add(new SmartParam
            {
                IsPositional = true,
                Index = 0,
                SourceName = "0",
                ClrName = "arg0",
                TypeName = "object"
            });
            model.Entries.Add(entry);

            var options = new EmitOptions
            {
                Namespace = "Localization",
                UseRuntimeAlias = true,
                SmartStrings = SmartStringMode.Methods,
                SmartParamTypes = SmartParamTypeMode.Inferred
            };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains(
                "public static string Greeting(object arg0)\n" +
                "            => __LT.GetString(TableName, \"Greeting\", arg0);",
                output);
            StringAssert.Contains("/// <param name=\"arg0\">positional {0}</param>", output);
        }

        [Test]
        public void SmartString_NamedOnlyUsesDictionary()
        {
            var model = new TableModel { Name = "Ui" };
            var entry = new EntryModel { Id = 1, Key = "Greeting", IsSmart = true };
            entry.Params.Add(new SmartParam
            {
                IsPositional = false,
                SourceName = "player-name",
                ClrName = "playerName",
                TypeName = "object"
            });
            model.Entries.Add(entry);

            var options = new EmitOptions
            {
                Namespace = "Localization",
                UseRuntimeAlias = true,
                SmartStrings = SmartStringMode.Methods
            };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains(
                "__LT.GetString(TableName, \"Greeting\", " +
                "new global::System.Collections.Generic.Dictionary<string, object> { [\"player-name\"] = playerName });",
                output);
        }

        [Test]
        public void SmartString_MixedUsesGetStringMixed()
        {
            var model = new TableModel { Name = "Ui" };
            var entry = new EntryModel { Id = 1, Key = "Greeting", IsSmart = true };
            entry.Params.Add(new SmartParam { IsPositional = true, Index = 0, SourceName = "0", ClrName = "arg0", TypeName = "object" });
            entry.Params.Add(new SmartParam { IsPositional = false, SourceName = "count", ClrName = "count", TypeName = "int" });
            model.Entries.Add(entry);

            var options = new EmitOptions
            {
                Namespace = "Localization",
                UseRuntimeAlias = true,
                SmartStrings = SmartStringMode.Methods
            };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains("__LT.GetStringMixed(TableName, \"Greeting\", new object[] { arg0 }, " +
                                  "new global::System.Collections.Generic.Dictionary<string, object> { [\"count\"] = count });",
                output);
        }

        [Test]
        public void Refs_EmitLocalizedStringAndLocalizedAssetMembers()
        {
            var model = new TableModel { Name = "Ui" };
            model.Entries.Add(new EntryModel { Id = 1, Key = "Title" });
            model.Entries.Add(new EntryModel { Id = 2, Key = "Sprite", AssetTypeName = "global::UnityEngine.Sprite" });

            var options = new EmitOptions
            {
                Namespace = "Localization",
                UseRuntimeAlias = true,
                Refs = true
            };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains("public static class Ref", output);
            StringAssert.Contains(
                "public static global::UnityEngine.Localization.LocalizedString Title => " +
                "new global::UnityEngine.Localization.LocalizedString(TableName, \"Title\");",
                output);
            StringAssert.Contains(
                "public static global::UnityEngine.Localization.LocalizedSprite Sprite => " +
                "new global::UnityEngine.Localization.LocalizedSprite(TableName, \"Sprite\");",
                output);
        }

        [Test]
        public void KeySeparators_CreateNestedClasses()
        {
            var model = Model("Ui", false, (1L, "Menu/Start"), (2L, "Menu/Quit"), (3L, "Title"));
            var options = new EmitOptions
            {
                Namespace = "Localization",
                UseRuntimeAlias = true,
                KeySeparators = "/",
                Naming = NamingConvention.PascalCase
            };
            CodeEmitter.AssignClassNames(new[] { model }, options);
            var output = CodeEmitter.Emit(model, options);

            StringAssert.Contains("public static class Menu", output);
            StringAssert.Contains("public static string Start =>", output);
            StringAssert.Contains("public static string Quit =>", output);
            StringAssert.Contains("public static string Title =>", output);
        }
    }
}
