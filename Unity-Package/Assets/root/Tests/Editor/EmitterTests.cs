            named.Params.Add(new SmartParam { SourceName = "count", ClrName = "count", TypeName = "int" });
            model.Entries.Add(named);

            var options = new EmitOptions
            {
                Namespace = "Localization",
                SmartStrings = SmartStringMode.Methods,
                Refs = true,
                UniTask = true
