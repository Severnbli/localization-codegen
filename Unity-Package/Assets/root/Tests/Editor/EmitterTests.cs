                "using System.Collections.Generic;\n" +
                "using System.Threading;\n" +
                "using Cysharp.Threading.Tasks;\n" +
                "using Severnbli.LocalizationCodegen;\n" +
                "using UnityEngine;\n" +
                "using UnityEngine.Localization;\n" +
                "\n" +
                "namespace Localization\n",
