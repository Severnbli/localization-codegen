        static TableModel StringModel(string name, params long[] ids)
        {
            var model = new TableModel { Name = name };
            foreach (var id in ids)
            {
                model.Entries.Add(new EntryModel
                {
                    Id = id,
                    Key = "Key" + id
                });
            }
            return model;
        }

        static TableModel Model(string name, bool isAsset, params (long Id, string Key)[] entries)
        {
            var model = new TableModel { Name = name, IsAsset = isAsset };
            foreach (var entry in entries)
            {
                model.Entries.Add(new EntryModel
                {
                    Id = entry.Id,
                    Key = entry.Key,
                    AssetTypeName = isAsset ? "UnityEngine.Object" : null
                });
            }
            return model;
        }

        static EmitOptions LegacyOptions()
        {
            return new EmitOptions
            {
                Namespace = "Localization",
                SmartStrings = SmartStringMode.Off,
                Naming = NamingConvention.Keep
            };
        }

        [Test]
        public void DefaultOptions_EmitPlainUsings()
        {
            var model = Model("Ui", false, (2L, "Title"), (1L, "Greeting"));
            var options = LegacyOptions();
            CodeEmitter.AssignClassNames(new[] { model }, options);

            var expected =
                "// <auto-generated by Localization Codegen>\n" +
                "// Table collection: Ui\n" +
                "using Severnbli.LocalizationCodegen;\n" +
                "\n" +
                "namespace Localization\n" +
                "{\n" +
                "    public static class Ui\n" +
                "    {\n" +
                "        public const string TableName = \"Ui\";\n" +
                "\n" +
                "        public static string Greeting => LocalizedTables.GetString(TableName, \"Greeting\");\n" +
                "\n" +
                "        public static string Title => LocalizedTables.GetString(TableName, \"Title\");\n" +
                "    }\n" +
                "}\n";

            Assert.AreEqual(expected, CodeEmitter.Emit(model, options));
        }

        [Test]
        public void Usings_ImportEveryReferencedNamespaceOnce()
        {
            var model = new TableModel { Name = "Ui" };
            model.Entries.Add(new EntryModel { Id = 1, Key = "Title" });
            model.Entries.Add(new EntryModel { Id = 2, Key = "Logo", AssetTypeName = "UnityEngine.Sprite" });
